/**
 * 生成器公用件:frontmatter(契约 3)、生成头(契约 4)、契约副本读取、vendored 登记读取。
 * 生成器只读 `contract/`,不访问网络与兄弟仓;输出一律 LF 无 BOM 末行换行。
 */
import { join } from 'node:path';
import { parseArgs, readJson, readText, readTextIfExists, repoRootFrom, toLf, writeLf } from '../lib/text.mjs';

export const CONTRACT_DIR = 'contract';
export const DOCS_DIR = join('src', 'content', 'docs');

export function contractPath(root, name) {
  return join(root, CONTRACT_DIR, ...name.split('/'));
}

export function readContractText(root, name) {
  return toLf(readText(contractPath(root, name)));
}

export function readContractJson(root, name) {
  return readJson(contractPath(root, name));
}

export function readVendored(root) {
  return readJson(contractPath(root, 'vendored.json'));
}

/** `lastVerified` = 该契约副本登记的 vendoredAt(契约 4);未登记即抛,生成器不得凭空造日期。 */
export function lastVerifiedFor(root, name) {
  const entry = readVendored(root)[name];
  if (!entry || typeof entry.vendoredAt !== 'string') {
    throw new Error(`contract/vendored.json 缺 ${name} 的 vendoredAt 登记;先跑 node scripts/vendor/index.mjs`);
  }
  return entry.vendoredAt;
}

function yamlString(s) {
  return `'${String(s).replace(/'/g, "''")}'`;
}

/**
 * frontmatter 契约 3:title / description / zone / category / related? / sources? / lastVerified / generated?。
 * 字符串一律单引号(日期不被 YAML 解析成 Date;`@` 起头等安全);数组行内形。
 */
export function frontmatter(fields) {
  const order = ['title', 'description', 'zone', 'category', 'related', 'sources', 'lastVerified', 'generated'];
  const lines = ['---'];
  for (const key of order) {
    if (!(key in fields) || fields[key] === undefined) continue;
    const v = fields[key];
    if (Array.isArray(v)) lines.push(`${key}: [${v.map(yamlString).join(', ')}]`);
    else if (typeof v === 'boolean') lines.push(`${key}: ${v ? 'true' : 'false'}`);
    else lines.push(`${key}: ${yamlString(v)}`);
  }
  lines.push('---');
  return lines.join('\n');
}

/** 契约 4 生成头(frontmatter 之后一行);不带换行,由调用方拼行。 */
export function generatedHeader(script, source) {
  return `<!-- generated by ${script} from ${source}; do not edit -->`;
}

/** Markdown 表格单元格:去换行、转义竖线。 */
export function cell(text) {
  return String(text ?? '').replace(/\r?\n/g, ' ').replace(/\|/g, '\\|').trim();
}

/** 单词边界(小写字母 / 数字 / 下划线为词字符)整词出现。 */
export function mentionsWord(text, word) {
  return new RegExp(`(^|[^a-z0-9_])${word.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}($|[^a-z0-9_])`).test(text);
}

/**
 * 与 Starlight(rehype-slug → github-slugger)同律的标题 slug:小写、去标点、每个空格换 `-`(不合并)。
 * 本仓生成页的标题只用「字母 / 数字 / 下划线 / 中文 / 单空格」,避免落入 slugger 的边角。
 */
export function slug(title) {
  return title
    .toLowerCase()
    .replace(/[^\p{L}\p{N}\s_-]/gu, '')
    .replace(/ /g, '-');
}

/**
 * 生成器统一入口:`generate(root) → [{ rel, content }]`(同步或 Promise 皆可;sdk-api 走 typedoc 为异步);
 * `--check` 与在库文件逐字节比对;`--root` 指向他处(卷用)。
 */
export async function runGenerator(mod, argv = process.argv.slice(2)) {
  const args = parseArgs(argv);
  const root = typeof args.root === 'string' ? args.root : repoRootFrom(import.meta.url);
  const outputs = (await mod.generate(root)).map((o) => ({ ...o, content: toLf(o.content) }));
  if (args.check) {
    const diff = outputs.filter((o) => readTextIfExists(join(root, o.rel)) !== o.content);
    if (diff.length) {
      console.error(`[gen:check] ${mod.SCRIPT} 再生有差:\n  ${diff.map((o) => o.rel).join('\n  ')}`);
      process.exit(1);
    }
    console.log(`[gen:check] ${mod.SCRIPT} ok(${outputs.length} 文件零 diff)`);
    return;
  }
  for (const o of outputs) {
    writeLf(join(root, o.rel), o.content);
    console.log(`[gen] wrote ${o.rel}`);
  }
}
