import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { existsSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { repoRootFrom } from '../lib/text.mjs';
import { slug } from './lib.mjs';
import { generate, loadNotes, OUT_REL, retryable } from './error-codes.mjs';

const root = repoRootFrom(import.meta.url);
const script = fileURLToPath(new URL('./error-codes.mjs', import.meta.url));
const openapi = JSON.parse(readFileSync(join(root, 'contract', 'openapi.json'), 'utf8'));
const catalog = openapi['x-tansr-error-codes'];
const vendored = JSON.parse(readFileSync(join(root, 'contract', 'vendored.json'), 'utf8'));

function headings(md, level) {
  const re = new RegExp(`^${'#'.repeat(level)} (.+)$`, 'gm');
  return [...md.matchAll(re)].map((m) => m[1]);
}

test('error-codes:码数 = vendored 契约条数,锚点 = 码名且唯一', () => {
  const [{ content }] = generate(root);
  const codes = headings(content, 3);
  assert.equal(codes.length, catalog.length);
  // 85 → 88:tansr-api@ed26af65(2026-10-05 vendor)新增 operation_input_invalid(400)/ operation_not_configured(503)/
  // upstream_outcome_unknown(502),皆来自 /t1 非对话操作面(tag nonchat);零删除。
  assert.equal(catalog.length, 88, '登记 88 码(原 85 + 3);契约变了请同步终报计数');
  for (const c of ['operation_input_invalid', 'operation_not_configured', 'upstream_outcome_unknown']) {
    assert.ok(catalog.some((e) => e.code === c), `tansr-api@ed26af65 起登记 ${c}`);
  }
  assert.deepEqual([...codes].sort(), catalog.map((e) => e.code).sort());
  assert.equal(new Set(codes).size, codes.length, '锚点重复');
  for (const c of codes) assert.match(c, /^[a-z0-9_]+$/, `码名 ${c} 不是合法锚点`);
  assert.ok(content.includes('### rate_limited\n'));
});

test('error-codes:frontmatter 契约 3 字段齐、第二行生成头(契约 4)', () => {
  const [{ content }] = generate(root);
  const lines = content.split('\n');
  assert.equal(lines[0], '---');
  const end = lines.indexOf('---', 1);
  const fm = lines.slice(1, end);
  assert.ok(fm.includes("title: '错误码参考'"));
  assert.ok(fm.includes("zone: 'docs'"));
  assert.ok(fm.includes("category: 'errors'"));
  assert.ok(fm.includes("sources: ['contract/openapi.json']"));
  assert.ok(fm.includes(`lastVerified: '${vendored['openapi.json'].vendoredAt}'`));
  assert.ok(fm.includes('generated: true'));
  assert.ok(fm.some((l) => l.startsWith('description: ')));
  assert.equal(lines[end + 1], '<!-- generated by scripts/gen/error-codes.mjs from contract/openapi.json; do not edit -->');
});

test('error-codes:每码一张表,HTTP 状态与契约一致;可重试按状态律', () => {
  const [{ content }] = generate(root);
  for (const e of catalog) {
    const i = content.indexOf(`### ${e.code}\n`);
    assert.ok(i !== -1, e.code);
    const block = content.slice(i, content.indexOf('\n### ', i + 1) === -1 ? undefined : content.indexOf('\n### ', i + 1));
    assert.match(block, new RegExp(`\\| ${e.status} \\| `), `${e.code} 状态 ${e.status}`);
  }
  assert.equal(retryable({ code: 'rate_limited', status: 429 }), '是(按 Retry-After 退避)');
  assert.equal(retryable({ code: 'upstream_error', status: 502 }), '是(退避后重试)');
  assert.equal(retryable({ code: 'payload_too_large', status: 413 }), '否');
  assert.equal(retryable({ code: 'device_code_pending', status: 400 }), '是(继续轮询)');
});

test('error-codes:令牌失效码带端侧提示与 detail.reason 取值', () => {
  const [{ content }] = generate(root);
  const i = content.indexOf('### unauthorized\n');
  const block = content.slice(i, i + 1200);
  assert.match(block, /清除本地令牌并重新登录/);
  assert.match(block, /`check_unavailable`/);
});

test('error-codes:分组表链接指向存在的二级标题', () => {
  const [{ content }] = generate(root);
  const h2 = new Set(headings(content, 2).map(slug));
  const links = [...content.matchAll(/\]\(#([^)]+)\)/g)].map((m) => m[1]);
  assert.ok(links.length > 0);
  for (const l of links) assert.ok(h2.has(l), `#${l} 无对应标题`);
});

test('error-codes:notes 键 ⊆ 契约码集(无陈旧条目)', () => {
  const notes = loadNotes(root);
  const codes = new Set(catalog.map((e) => e.code));
  for (const k of Object.keys(notes)) assert.ok(codes.has(k), `notes 有契约外的码 ${k}`);
});

test('error-codes:在库页面存在且再生零 diff(--check exit 0)', () => {
  const p = join(root, OUT_REL);
  assert.ok(existsSync(p), `${OUT_REL} 须已生成并提交`);
  const [{ content }] = generate(root);
  assert.equal(readFileSync(p, 'utf8'), content);
  const r = spawnSync(process.execPath, [script, '--check'], { encoding: 'utf8' });
  assert.equal(r.status, 0, r.stdout + r.stderr);
});
