test('cli-commands:每子命令一节 ## <cmd>,数 = cli-help.json commands 数,锚点唯一;全局帮助原文入代码块', () => {
  const doc = JSON.parse(readFileSync(join(root, 'contract', 'cli-help.json'), 'utf8'));
  const [{ content, stats }] = cliCommands.generate(root);
  assertContract(content, { title: 'CLI 命令参考', category: 'cli', source: 'cli-help.json', script: 'scripts/gen/cli-commands.mjs' });
  const h2 = h(content, 2);
  assert.equal(stats.commands, doc.commands.length);
  assert.deepEqual(h2.slice(1), doc.commands.map((c) => c.command));
  assert.equal(new Set(h2.map(slug)).size, h2.length);
  assert.ok(content.includes(doc.top.help.replace(/\n$/, '')), '顶层 help 原文须逐字在页内');
  assert.ok(h2.includes('mcp serve') && slug('mcp serve') === 'mcp-serve');
  for (const c of doc.commands) {
    if (c.help !== doc.top.help) assert.ok(content.includes(c.help.replace(/\n$/, '')), `${c.command} help 原文`);
  }
});

