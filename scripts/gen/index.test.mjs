test('releases:三包各一页;顶部用户口吻层每版一节(三段 / note;「未发」标注)+ <details> 折叠 CHANGELOG 原文(标题降两级、逐字);折叠段外零内部编号', () => {
  const outputs = releases.generate(root);
  assert.equal(outputs.length, 3);
  const notes = JSON.parse(readFileSync(join(root, 'contract', releases.NOTES_SOURCE), 'utf8'));
  for (const pkg of releases.PACKAGES) {
    const o = outputs.find((x) => x.rel === releases.outRel(pkg.id));
    const src = readFileSync(join(root, 'contract', ...pkg.source.split('/')), 'utf8');
    const { title, body } = releases.splitChangelog(src);
    const { fields, afterLine } = fm(o.content);
    assert.ok(fields.includes(`title: '${title.replace(/'/g, "''")}'`));
    assert.ok(fields.includes("zone: 'docs'") && fields.includes("category: 'releases'") && fields.includes('generated: true'));
    assert.ok(fields.includes(`sources: ['contract/${pkg.source}', 'contract/${releases.NOTES_SOURCE}']`), '两事实源皆登 sources');
    assert.ok(fields.includes(`lastVerified: '${vendored[pkg.source].vendoredAt}'`));
    assert.equal(afterLine, `<!-- generated by scripts/gen/releases.mjs from contract/${pkg.source}; do not edit -->`);
    // 折叠段:原文逐字(仅标题降两级),被 internal-changelog 标记包夹
    const open = o.content.indexOf(releases.INTERNAL_OPEN);
    const close = o.content.indexOf(releases.INTERNAL_CLOSE);
    assert.ok(open > 0 && close > open, '折叠段标记成对');
    const folded = o.content.slice(open + releases.INTERNAL_OPEN.length, close).replace(/^\n+/, '').replace(/\n+$/, '');
    assert.equal(folded, releases.demoteHeadings(body.replace(/\n+$/, '')), `${pkg.id} 折叠段非逐字(降级后)`);
    const stripHashes = (t) => t.replace(/^#+(?=\s)/gm, '');
    assert.equal(stripHashes(folded), stripHashes(body.replace(/\n+$/, '')), '降级只改 # 数不改字');
    assert.ok(o.content.indexOf('<details>') < open && o.content.indexOf('</details>') > close);
    assert.ok(o.content.includes(`<summary>${releases.DETAILS_SUMMARY}</summary>`));
    // 用户口吻层:CHANGELOG 每版本段一个 h2,顺序同源;三段标题只在 h3;折叠段外无内部编号
    const visible = o.content.slice(0, o.content.indexOf('<details>'));
    const sections = releases.parseVersionSections(body);
    assert.equal(h(visible, 2).length, sections.length, `${pkg.id} 版本节数须 = CHANGELOG 版本段数`);
    sections.forEach((s, i) => {
      assert.ok(h(visible, 2)[i].startsWith(`${s.version}(`) || h(visible, 2)[i] === s.version, `${pkg.id} 第 ${i + 1} 节 ${h(visible, 2)[i]} 应为 ${s.version}`);
      if (s.unreleased) assert.ok(h(visible, 2)[i].endsWith('(未发)'), `${s.version} 须标「未发」`);
      const entry = notes[pkg.id][s.version];
      assert.ok(entry, `release-notes.json 须有 ${pkg.id} ${s.version}`);
      for (const sec of releases.SECTIONS) for (const it of entry[sec.key]) assert.ok(visible.includes(`- ${it.trim()}`), `${pkg.id} ${s.version} 缺条目:${it.slice(0, 30)}`);
      if (entry.note) assert.ok(visible.includes(entry.note.trim()));
    });
    for (const t of h(visible, 3)) assert.ok(releases.SECTIONS.some((sec) => sec.label === t), `h3 只许三段名,见 ${t}`);
    assert.doesNotMatch(visible, /FX-|W[1-5] 回执|泳道|收编|回执|卡号/, `${pkg.id} 折叠段外含内部编号`);
    assert.ok(o.stats.sections >= 1);
  }
  const cli = outputs.find((x) => x.rel === releases.outRel('cli')).content;
  assert.ok(/^## 0\.5\.0\(未发\)$/m.test(cli), '「未发」版本照 CHANGELOG 标注');
  assert.ok(/^> 未发/m.test(cli), '折叠段内「未发」原文保留');
  assert.ok(/^## 0\.4\.0\(2026-09-06\)$/m.test(cli), '已发版本带日期');
});

test('releases:parseVersionSections / demoteHeadings / renderUserSection 纯函数', () => {
  const body = '> 引言\n\n## 1.2.0\n\n> 未发(候发版)。\n\n### A\n\n- x\n\n## 1.1.0 (2026-01-02;随 y 发版)\n\n- 追溯。\n\n## 1.0.x (2025-12-01 … 2025-12-09)\n\n- z\n';
  const s = releases.parseVersionSections(body);
  assert.deepEqual(
    s.map(({ version, date, unreleased }) => ({ version, date, unreleased })),
    [
      { version: '1.2.0', date: undefined, unreleased: true },
      { version: '1.1.0', date: '2026-01-02', unreleased: false },
      { version: '1.0.x', date: '2025-12-01', unreleased: false },
    ],
  );
  assert.equal(s[0].body, '> 未发(候发版)。\n\n### A\n\n- x');
  assert.equal(releases.demoteHeadings('## a\n### b\n#### c\n##### d\n###### e\n```md\n## 码内不动\n```\n#no-space\n'), '#### a\n##### b\n###### c\n###### d\n###### e\n```md\n## 码内不动\n```\n#no-space\n');
  assert.equal(
    releases.renderUserSection(s[1], { date: '2026-01-02', added: ['甲'], changed: [], fixed: ['乙'] }),
    '## 1.1.0(2026-01-02)\n\n### 新增\n\n- 甲\n\n### 修复\n\n- 乙',
  );
  assert.equal(releases.renderUserSection(s[0], { added: [], changed: [], fixed: [], note: '无用户可见变更' }), '## 1.2.0(未发)\n\n> 本版尚未发布;以下为候发内容,以实际发版为准。\n\n无用户可见变更');
  assert.equal(releases.renderUserSection(s[2], { added: ['丙'], changed: [], fixed: [] }), '## 1.0.x(2025-12-01)\n\n### 新增\n\n- 丙');
  assert.throws(() => releases.renderUserSection(s[1], undefined), /缺版本 1\.1\.0/);
  assert.throws(() => releases.renderUserSection(s[1], { added: [], changed: [], fixed: [] }), /三段皆空又无 note/);
});

// ———— index(汇总门) ————
test('gen index:全部生成器在库零 diff(checkAll ok;--check exit 0)', async () => {
  for (const g of GENERATORS) for (const o of await g.generate(root)) assert.ok(existsSync(join(root, o.rel)), `${o.rel} 须已生成并提交`);
  const r = await checkAll(root, () => {});
  assert.deepEqual(r, { ok: true, differing: [], missing: [] });
  const p = spawnSync(process.execPath, [indexScript, '--check'], { encoding: 'utf8' });
  assert.equal(p.status, 0, p.stdout + p.stderr);
  assert.match(p.stdout, /全部生成物零 diff/);
});

test('gen index --check:改一字节 / 删一文件 → 红(exit 1 并列出文件)', async () => {
  const tmp = mkdtempSync(join(tmpdir(), 'tansr-docs-gen-red-'));
  try {
    cpSync(join(root, 'contract'), join(tmp, 'contract'), { recursive: true });
    cpSync(join(root, 'scripts'), join(tmp, 'scripts'), { recursive: true });
    cpSync(join(root, 'src'), join(tmp, 'src'), { recursive: true });
    const green = spawnSync(process.execPath, [indexScript, '--check', '--root', tmp], { encoding: 'utf8' });
    assert.equal(green.status, 0, green.stdout + green.stderr);
    const target = join(tmp, 'src', 'content', 'docs', 'errors', 'codes.md');
    writeFileSync(target, readFileSync(target, 'utf8').replace('| 429 |', '| 430 |'), 'utf8');
    rmSync(join(tmp, 'src', 'content', 'docs', 'releases', 'sdk.md'));
    const red = spawnSync(process.execPath, [indexScript, '--check', '--root', tmp], { encoding: 'utf8' });
    assert.equal(red.status, 1);
    assert.match(red.stdout + red.stderr, /DIFF\s+src[\\/]content[\\/]docs[\\/]errors[\\/]codes\.md/);
    assert.match(red.stdout + red.stderr, /MISSING\s+src[\\/]content[\\/]docs[\\/]releases[\\/]sdk\.md/);
    const all = await generateAll(root);
    assert.equal(all.filter((o) => !o.rel.split('\\').join('/').includes('/sdk/api/')).length, 7, 'sdk/api 之外仍是 7 件');
    assert.equal(all.length, 7 + (await sdkApi.generate(root)).length);
  } finally {
    rmSync(tmp, { recursive: true, force: true });
  }
});
