const root = repoRootFrom(import.meta.url);
const indexScript = fileURLToPath(new URL('./index.mjs', import.meta.url));
const vendored = JSON.parse(readFileSync(join(root, 'contract', 'vendored.json'), 'utf8'));

function fm(content) {
  const lines = content.split('\n');
  assert.equal(lines[0], '---');
  const end = lines.indexOf('---', 1);
  return { fields: lines.slice(1, end), afterLine: lines[end + 1] };
}

function assertContract(content, { title, category, source, script }) {
  const { fields, afterLine } = fm(content);
  assert.ok(fields.includes(`title: '${title.replace(/'/g, "''")}'`), fields.join('\n'));
  assert.ok(fields.some((l) => l.startsWith('description: ')));
  assert.ok(fields.includes("zone: 'docs'"));
  assert.ok(fields.includes(`category: '${category}'`));
  assert.ok(fields.includes(`sources: ['contract/${source}']`));
  assert.ok(fields.includes(`lastVerified: '${vendored[source].vendoredAt}'`));
  assert.ok(fields.includes('generated: true'));
  assert.equal(afterLine, `<!-- generated by ${script} from contract/${source}; do not edit -->`);
}

const h = (md, level) => [...md.matchAll(new RegExp(`^${'#'.repeat(level)} (.+)$`, 'gm'))].map((m) => m[1]);

// ———— serve-env ————
test('serve-env:解析 .env.example 注释形 → 30 键、组 / 类型 / 缺省 / 敏感齐;头注键数对表', () => {
  const text = readFileSync(join(root, 'contract', 'serve.env.example'), 'utf8');
  const parsed = serveEnv.parseEnvExample(text);
  const keys = parsed.groups.flatMap((g) => g.keys);
  assert.equal(keys.length, 30);
  assert.equal(parsed.declaredCount, 30);
  assert.ok(parsed.groups.length >= 5);
  for (const k of keys) {
    assert.match(k.key, /^TANSR_SERVE_[A-Z0-9_]+$/);
    assert.notEqual(k.path, '', `${k.key} 缺运行时选项路径`);
    assert.notEqual(k.spec, '', `${k.key} 缺取值形`);
  }
  const secret = keys.filter((k) => k.sensitive).map((k) => k.key);
  assert.deepEqual(secret, ['TANSR_SERVE_NOTIFY_SECRET']);
  assert.ok(parsed.outside.includes('TANSR_SERVE_TOKEN'), '头注点名的入口级键须被识别(供 #tansr_serve_token 锚点)');
});

test('serve-env:页面 frontmatter 契约、键锚点 = 小写键名且唯一、总表 30 行', () => {
  const [{ content, stats }] = serveEnv.generate(root);
  assertContract(content, { title: 'serve 环境变量', category: 'serve', source: 'serve.env.example', script: 'scripts/gen/serve-env.mjs' });
  assert.equal(stats.keys, 30);
  const h3 = h(content, 3);
  assert.equal(new Set(h3).size, h3.length);
  assert.equal(h3.filter((x) => x.startsWith('TANSR_SERVE_')).length, 30 + stats.outside);
  assert.ok(h3.includes('TANSR_SERVE_TOKEN'));
  assert.equal(slug('TANSR_SERVE_TOKEN'), 'tansr_serve_token');
  const rows = content.split('\n').filter((l) => /^\| \[`TANSR_SERVE_/.test(l));
  assert.equal(rows.length, 30);
  for (const l of [...content.matchAll(/\]\(#([^)]+)\)/g)].map((m) => m[1])) {
    assert.ok(h3.map(slug).includes(l) || h(content, 2).map(slug).includes(l), `#${l} 无对应标题`);
  }
});

// ———— cli-commands ————
test('cli-commands:每子命令一节 ## <cmd>,数 = cli-help.json commands 数,锚点唯一;全局帮助原文入代码块', () => {
  const doc = JSON.parse(readFileSync(join(root, 'contract', 'cli-help.json'), 'utf8'));
  const [{ content, stats }] = cliCommands.generate(root);
  assertContract(content, { title: 'CLI 命令参考', category: 'cli', source: 'cli-help.json', script: 'scripts/gen/cli-commands.mjs' });
  const h2 = h(content, 2);
  assert.equal(stats.commands, doc.commands.length);
  assert.deepEqual(h2.slice(1), doc.commands.map((c) => c.command));
  assert.equal(new Set(h2.map(slug)).size, h2.length);
  assert.ok(content.includes(doc.top.help.replace(/\n$/, '')), '顶层 help 原文须逐字在页内');
  assert.ok(h2.includes('mcp serve') && slug('mcp serve') === 'mcp-serve');
  for (const c of doc.commands) {
    if (c.help !== doc.top.help) assert.ok(content.includes(c.help.replace(/\n$/, '')), `${c.command} help 原文`);
  }
});

// ———— releases ————
test('releases:三包各一页,正文 = CHANGELOG 去 H1 后逐字节;「未发」段原样', () => {
  const outputs = releases.generate(root);
  assert.equal(outputs.length, 3);
  for (const pkg of releases.PACKAGES) {
    const o = outputs.find((x) => x.rel === releases.outRel(pkg.id));
    const src = readFileSync(join(root, 'contract', ...pkg.source.split('/')), 'utf8');
    const { title, body } = releases.splitChangelog(src);
    assertContract(o.content, { title, category: 'releases', source: pkg.source, script: 'scripts/gen/releases.mjs' });
    const headerEnd = o.content.indexOf('; do not edit -->\n\n') + '; do not edit -->\n\n'.length;
    assert.equal(o.content.slice(headerEnd), body, `${pkg.id} 正文非逐字`);
    assert.ok(o.stats.sections >= 1);
  }
  const cli = outputs.find((x) => x.rel === releases.outRel('cli')).content;
  assert.ok(/^> 未发/m.test(cli), '「未发」段须原样保留');
});

// ———— index(汇总门) ————
test('gen index:全部生成器在库零 diff(checkAll ok;--check exit 0)', async () => {
  for (const g of GENERATORS) for (const o of await g.generate(root)) assert.ok(existsSync(join(root, o.rel)), `${o.rel} 须已生成并提交`);
  const r = await checkAll(root, () => {});
  assert.deepEqual(r, { ok: true, differing: [], missing: [] });
  const p = spawnSync(process.execPath, [indexScript, '--check'], { encoding: 'utf8' });
  assert.equal(p.status, 0, p.stdout + p.stderr);
  assert.match(p.stdout, /全部生成物零 diff/);
});

test('gen index --check:改一字节 / 删一文件 → 红(exit 1 并列出文件)', async () => {
  const tmp = mkdtempSync(join(tmpdir(), 'tansr-docs-gen-red-'));
  try {
    cpSync(join(root, 'contract'), join(tmp, 'contract'), { recursive: true });
    cpSync(join(root, 'scripts'), join(tmp, 'scripts'), { recursive: true });
    cpSync(join(root, 'src'), join(tmp, 'src'), { recursive: true });
    const green = spawnSync(process.execPath, [indexScript, '--check', '--root', tmp], { encoding: 'utf8' });
    assert.equal(green.status, 0, green.stdout + green.stderr);
    const target = join(tmp, 'src', 'content', 'docs', 'errors', 'codes.md');
    writeFileSync(target, readFileSync(target, 'utf8').replace('| 429 |', '| 430 |'), 'utf8');
    rmSync(join(tmp, 'src', 'content', 'docs', 'releases', 'sdk.md'));
    const red = spawnSync(process.execPath, [indexScript, '--check', '--root', tmp], { encoding: 'utf8' });
    assert.equal(red.status, 1);
    assert.match(red.stdout + red.stderr, /DIFF\s+src[\\/]content[\\/]docs[\\/]errors[\\/]codes\.md/);
    assert.match(red.stdout + red.stderr, /MISSING\s+src[\\/]content[\\/]docs[\\/]releases[\\/]sdk\.md/);
    const all = await generateAll(root);
    assert.equal(all.filter((o) => !o.rel.split('\\').join('/').includes('/sdk/api/')).length, 7, 'sdk/api 之外仍是 7 件');
    assert.equal(all.length, 7 + (await sdkApi.generate(root)).length);
  } finally {
    rmSync(tmp, { recursive: true, force: true });
  }
});
