const root = repoRootFrom(import.meta.url);
const indexScript = fileURLToPath(new URL('./index.mjs', import.meta.url));
const vendored = JSON.parse(readFileSync(join(root, 'contract', 'vendored.json'), 'utf8'));

function fm(content) {
  const lines = content.split('\n');
  assert.equal(lines[0], '---');
  const end = lines.indexOf('---', 1);
  return { fields: lines.slice(1, end), afterLine: lines[end + 1] };
}

function assertContract(content, { title, category, source, script }) {
  const { fields, afterLine } = fm(content);
  assert.ok(fields.includes(`title: '${title.replace(/'/g, "''")}'`), fields.join('\n'));
  assert.ok(fields.some((l) => l.startsWith('description: ')));
  assert.ok(fields.includes("zone: 'docs'"));
  assert.ok(fields.includes(`category: '${category}'`));
  assert.ok(fields.includes(`sources: ['contract/${source}']`));
  assert.ok(fields.includes(`lastVerified: '${vendored[source].vendoredAt}'`));
  assert.ok(fields.includes('generated: true'));
  assert.equal(afterLine, `<!-- generated by ${script} from contract/${source}; do not edit -->`);
}

const h = (md, level) => [...md.matchAll(new RegExp(`^${'#'.repeat(level)} (.+)$`, 'gm'))].map((m) => m[1]);

// ———— serve-env ————
test('serve-env:解析 .env.example 注释形 → 30 键、组 / 类型 / 缺省 / 敏感齐;头注键数对表', () => {
  const text = readFileSync(join(root, 'contract', 'serve.env.example'), 'utf8');
  const parsed = serveEnv.parseEnvExample(text);
  const keys = parsed.groups.flatMap((g) => g.keys);
  assert.equal(keys.length, 30);
  assert.equal(parsed.declaredCount, 30);
  assert.ok(parsed.groups.length >= 5);
  for (const k of keys) {
    assert.match(k.key, /^TANSR_SERVE_[A-Z0-9_]+$/);
    assert.notEqual(k.path, '', `${k.key} 缺运行时选项路径`);
    assert.notEqual(k.spec, '', `${k.key} 缺取值形`);
  }
  const secret = keys.filter((k) => k.sensitive).map((k) => k.key);
  assert.deepEqual(secret, ['TANSR_SERVE_NOTIFY_SECRET']);
  assert.ok(parsed.outside.includes('TANSR_SERVE_TOKEN'), '头注点名的入口级键须被识别(供 #tansr_serve_token 锚点)');
});

test('serve-env:页面 frontmatter 契约、键锚点 = 小写键名且唯一、总表 30 行', () => {
  const [{ content, stats }] = serveEnv.generate(root);
  assertContract(content, { title: 'serve 环境变量', category: 'serve', source: 'serve.env.example', script: 'scripts/gen/serve-env.mjs' });
  assert.equal(stats.keys, 30);
  const h3 = h(content, 3);
  assert.equal(new Set(h3).size, h3.length);
  assert.equal(h3.filter((x) => x.startsWith('TANSR_SERVE_')).length, 30 + stats.outside);
  assert.ok(h3.includes('TANSR_SERVE_TOKEN'));
  assert.equal(slug('TANSR_SERVE_TOKEN'), 'tansr_serve_token');
  const rows = content.split('\n').filter((l) => /^\| \[`TANSR_SERVE_/.test(l));
  assert.equal(rows.length, 30);
  for (const l of [...content.matchAll(/\]\(#([^)]+)\)/g)].map((m) => m[1])) {
    assert.ok(h3.map(slug).includes(l) || h(content, 2).map(slug).includes(l), `#${l} 无对应标题`);
  }
});

