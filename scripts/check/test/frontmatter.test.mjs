import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, mkdirSync, writeFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { CODES, checkFrontmatter, fileToSlug, parseFrontmatter } from '../frontmatter.mjs';

function root() {
  const r = mkdtempSync(join(tmpdir(), 'ds-frontmatter-'));
  mkdirSync(join(r, 'src', 'content', 'docs', 'errors'), { recursive: true });
  mkdirSync(join(r, 'src', 'content', 'docs', 'support'), { recursive: true });
  mkdirSync(join(r, 'src', 'content', 'docs', 'en', 'support'), { recursive: true });
  mkdirSync(join(r, 'contract'), { recursive: true });
  writeFileSync(join(r, 'contract', 'openapi.json'), '{}\n');
  return r;
}
const docs = (r, f) => join(r, 'src', 'content', 'docs', f);

test('frontmatter 绿:字段齐 / 枚举合法 / related 存在 / sources 存在或合形 / 生成页带 generated + 标记', () => {
  const r = root();
  try {
    writeFileSync(
      docs(r, 'support/faq.md'),
      `---
title: FAQ
description: 帮助。
zone: support
category: support
related:
  - errors/codes
sources:
  - contract/openapi.json
  - tansr-cli:doc/11-用户手册.md
lastVerified: 2026-09-08
---

正文。
`,
    );
    writeFileSync(
      docs(r, 'errors/codes.md'),
      `---
title: 错误码表
description: 生成。
zone: docs
category: errors
lastVerified: '2026-09-08'
generated: true
---
<!-- generated by scripts/gen/error-codes.mjs from contract/openapi.json; do not edit -->

表。
`,
    );
    writeFileSync(
      docs(r, 'en/support/faq.md'),
      `---
title: FAQ
description: Help.
zone: support
category: support
related: [errors/codes]
lastVerified: 2026-09-08
---

Body.
`,
    );
    const res = checkFrontmatter({ root: r });
    assert.deepEqual(res.errors, []);
    assert.equal(res.summary.files, 3);
  } finally {
    rmSync(r, { recursive: true, force: true });
  }
});

test('frontmatter 红:缺字段 / 坏枚举 / 坏日期 / related 不存在 / sources 不存在 / 生成页缺 generated / generated 缺标记', () => {
  const r = root();
  try {
    writeFileSync(
      docs(r, 'support/bad.md'),
      `---
title: 坏
zone: help
category: misc
related:
  - errors/nope
  - Bad/Slug
sources:
  - contract/missing.json
  - random-string
lastVerified: 2026/09/08
---

正文。
`,
    );
    writeFileSync(
      docs(r, 'errors/codes.md'),
      `---
title: 错误码表
description: 生成页忘了 generated。
zone: docs
category: errors
lastVerified: 2026-09-08
---
<!-- generated by scripts/gen/error-codes.mjs from contract/openapi.json; do not edit -->

表。
`,
    );
    writeFileSync(
      docs(r, 'support/flagged.md'),
      `---
title: 标了 generated 却无标记
description: x
zone: support
category: support
lastVerified: 2026-09-08
generated: true
---

正文。
`,
    );
    writeFileSync(docs(r, 'support/nofm.md'), '# 无 frontmatter\n');
    const res = checkFrontmatter({ root: r });
    const codes = res.errors.map((e) => `${e.file.replace('src/content/docs/', '')}:${e.code}:${e.detail}`);
    assert.ok(codes.includes(`support/bad.md:${CODES.MISSING}:description`), codes.join('\n'));
    assert.ok(codes.includes(`support/bad.md:${CODES.BAD_ZONE}:help`));
    assert.ok(codes.includes(`support/bad.md:${CODES.BAD_CATEGORY}:misc`));
    assert.ok(codes.includes(`support/bad.md:${CODES.BAD_DATE}:2026/09/08`));
    assert.ok(codes.includes(`support/bad.md:${CODES.RELATED_MISSING}:errors/nope`));
    assert.ok(codes.includes(`support/bad.md:${CODES.BAD_RELATED}:Bad/Slug`));
    assert.ok(codes.includes(`support/bad.md:${CODES.SOURCE_MISSING}:contract/missing.json`));
    assert.ok(codes.includes(`support/bad.md:${CODES.BAD_SOURCE}:random-string`));
    assert.ok(codes.includes(`errors/codes.md:${CODES.GENERATED_FLAG}:has generated marker`));
    assert.ok(codes.some((c) => c.startsWith(`support/flagged.md:${CODES.GENERATED_MARKER}`)));
    assert.ok(codes.some((c) => c.startsWith(`support/nofm.md:${CODES.NO_FRONTMATTER}`)));
    assert.equal(res.summary.errors, 11);
  } finally {
    rmSync(r, { recursive: true, force: true });
  }
});

test('frontmatter 纯函数:YAML 子集解析与 slug 映射', () => {
  const p = parseFrontmatter(`---
title: "带引号"
template: splash
hero:
  title: x
  actions:
    - text: a
tags: [a, 'b', "c"]
lastVerified: 2026-09-08
generated: true
empty:
---
body
`);
  assert.equal(p.data.title, '带引号');
  assert.equal(p.data.template, 'splash');
  assert.deepEqual(p.data.hero, { __object: true });
  assert.deepEqual(p.data.tags, ['a', 'b', 'c']);
  assert.equal(p.data.lastVerified, '2026-09-08');
  assert.equal(p.data.generated, true);
  assert.equal(p.data.empty, null);
  assert.equal(p.body, 'body\n');
  assert.equal(parseFrontmatter('no fm\n'), null);
  assert.equal(fileToSlug('index.mdx'), '');
  assert.equal(fileToSlug('support/index.mdx'), 'support');
  assert.equal(fileToSlug('errors/codes.md'), 'errors/codes');
  assert.equal(fileToSlug('en/support/faq.md'), 'en/support/faq');
});
